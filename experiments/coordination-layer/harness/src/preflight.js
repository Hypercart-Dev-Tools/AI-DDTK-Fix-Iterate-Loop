'use strict';

// Preflight phase — the "let the agents ask questions before any work" step.
//
// Each participating agent is given the spec + its candidate task list in a
// READ-ONLY prompt and asked to surface clarifying questions (or NO_QUESTIONS).
// We capture each agent's questions, write a combined QUESTIONS.md, and STOP at
// a human gate — the run does not start until a human reviews the questions
// (and, ideally, edits the spec to answer them). `--auto` skips the gate for
// unattended/CI use.

const fs = require('fs');
const path = require('path');
const { getDriver } = require('./drivers');
const { buildPreflightPrompt } = require('./prompts');
const { runProc } = require('./proc');

// Pull clarifying questions out of an agent's free-text output. We accept a
// loose contract: any line containing "QUESTION:" is a question; a line that is
// exactly NO_QUESTIONS (case-insensitive) means none.
function extractQuestions(output) {
  const lines = output.split('\n');
  const questions = lines
    .filter(l => /question:/i.test(l))
    .map(l => l.replace(/^.*?question:\s*/i, '').trim())
    .filter(Boolean);
  const explicitNone = lines.some(l => /^\s*\[?[\w-]*\]?\s*no_questions\s*$/i.test(l));
  return { questions, explicitNone };
}

async function runPreflight({ rec, spec, agents, workdir, tickBin, specPath, timeoutMs }) {
  rec.event('preflight.start', { agents: agents.map(a => `${a.id}:${a.driver}`).join(',') });
  const perAgent = {};

  for (const agentSpec of agents) {
    const driver = getDriver(agentSpec.driver);
    const prompt = buildPreflightPrompt({
      agent: agentSpec.id,
      project: spec.project,
      tasks: spec.tasks,
      workdir,
    });
    const ss = driver.spawnSpec({
      mode: 'preflight',
      agent: agentSpec.id,
      prompt,
      workdir,
      specPath,
      tickBin,
    });
    const logStream = rec.logStreamFor(`preflight-${agentSpec.id}`);
    const result = await runProc({
      cmd: ss.cmd, args: ss.args, input: ss.input,
      cwd: workdir, env: { ...process.env, TICK_REPO_ROOT: workdir },
      logStream, timeoutMs,
    });
    logStream.end();

    const { questions, explicitNone } = extractQuestions(result.output);
    perAgent[agentSpec.id] = { driver: driver.name, questions, explicitNone, exit: result.code };
    rec.event('preflight.agent', {
      agent: agentSpec.id, driver: driver.name,
      questions: questions.length, exit: result.code,
    });
  }

  const md = renderQuestionsMd(spec, perAgent);
  const qPath = path.join(rec.runDir, 'preflight', 'QUESTIONS.md');
  fs.mkdirSync(path.dirname(qPath), { recursive: true });
  fs.writeFileSync(qPath, md);
  rec.event('preflight.end', { questions_file: path.relative(rec.runDir, qPath) });

  const totalQuestions = Object.values(perAgent).reduce((n, a) => n + a.questions.length, 0);
  return { perAgent, totalQuestions, questionsPath: qPath };
}

function renderQuestionsMd(spec, perAgent) {
  const out = [];
  out.push(`# Preflight questions — ${spec.project.name}`);
  out.push('');
  out.push('> Generated by the trial harness preflight phase. Review these, edit the');
  out.push('> project spec to answer anything material, then start the run.');
  out.push('');
  for (const [agent, data] of Object.entries(perAgent)) {
    out.push(`## ${agent} (${data.driver})`);
    out.push('');
    if (data.questions.length === 0) {
      out.push(data.explicitNone ? '- _No questions._' : '- _No questions detected in output._');
    } else {
      for (const q of data.questions) out.push(`- [ ] ${q}`);
    }
    out.push('');
  }
  return out.join('\n');
}

module.exports = { runPreflight, extractQuestions };
